let m = 101;

if (m < 0 || m > 100) {
    console.log("Invalid marks");
} else if (m >= 90) {
    console.log("A");
} else if (m >= 80) {
    console.log("B");
} else if (m >= 70) {
    console.log("C");
} else if (m >= 60) {
    console.log("D");
} else if (m >= 50) {
    console.log("E");
} else {
    console.log("F");
}